export type TextKey = keyof typeof fr;
export const TABLES: Record<Lang, Record<TextKey, string>> = { fr, en };

/** Traducteur : `t(clé, { n: 2 })` ; clé inconnue : le français, puis la clé. */
export function makeT(lang: Lang): (key: string, vars?: Record<string, string | number>) => string {
  return (key, vars) => {
    const s = (TABLES[lang] as Record<string, string>)[key] ?? (TABLES.fr as Record<string, string>)[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}
